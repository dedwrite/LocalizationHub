test('prerendered Home and Product remain navigable without JavaScript', async ({browser}) => {
  const context = await browser.newContext({javaScriptEnabled: false})
  const page = await context.newPage()
  await page.goto('http://127.0.0.1:8787/')
  await expect(page.getByRole('heading', {name: 'The editor is the product.'})).toBeVisible()
  await page.getByRole('link', {name: 'Product details →'}).click()
  await expect(page).toHaveURL(/\/product$/)
  await expect(page.locator('#context')).toBeVisible()
  await context.close()
})
