test('offscreen pause and keyboard access at laptop width', async ({page, browserName}) => {
  await page.clock.install({time: new Date('2026-10-07T00:00:00Z')})
  await page.clock.pauseAt(new Date('2026-10-07T00:00:01Z'))
  await page.setViewportSize({width: 1280, height: 150})
  await page.goto('/')
  await expect(page.locator('.home-editor')).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('.home-editor')).toHaveAttribute('data-visible', 'false')
  await page.clock.runFor(10000)
  await expect(page.locator('.home-editor')).toHaveAttribute('data-stage', 'select')
  await page.setViewportSize({width: 1280, height: 900})
  await page.clock.resume()
  await page.keyboard.press('Tab')
  if (browserName === 'webkit') {
    // Windows WebKit defaults to form-only Tab traversal. Do not change the
    // user's OS preference: verify its native stop, then link activation.
    await expect(page.getByRole('combobox', {name: 'Interface language'})).toBeFocused()
    await page.locator('.home-skip').focus()
  }
  await expect(page.locator('.home-skip')).toBeFocused()
  await page.keyboard.press('Enter')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.locator('#demo-target').focus()
  await expect(page.locator('.home-editor')).toHaveAttribute('data-paused', 'true')
})
test('hidden document and offscreen editor suspend automatic progression', async ({page}) => {
  await page.clock.install({time: new Date('2026-10-07T00:00:00Z')})
  await page.clock.pauseAt(new Date('2026-10-07T00:00:01Z'))
  await page.goto('/')
  await expect(page.locator('.home-editor')).toHaveAttribute('data-ready', 'true')
  await expect(page.locator('.home-editor')).toHaveAttribute('data-stage', 'select')
  await page.evaluate(() => {Object.defineProperty(document, 'visibilityState', {configurable: true, value: 'hidden'}); document.dispatchEvent(new Event('visibilitychange'))})
  await expect(page.locator('.home-editor')).toHaveAttribute('data-visible', 'false')
  await page.clock.runFor(10000)
  await expect(page.locator('.home-editor')).toHaveAttribute('data-stage', 'select')
  await page.evaluate(() => {Object.defineProperty(document, 'visibilityState', {configurable: true, value: 'visible'}); document.dispatchEvent(new Event('visibilitychange'))})
  await expect(page.locator('.home-editor')).toHaveAttribute('data-visible', 'true')
  await page.clock.runFor(1900)
  await expect(page.locator('.home-editor')).toHaveAttribute('data-stage', 'translate')
})
