test('Product controls pause the story, preserve edits and restore the review example', async ({page}) => {
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto('/product')
  const context = page.locator('.pd-context')
  await context.scrollIntoViewIfNeeded()
  await expect(context).toHaveAttribute('data-visible','true')
  await context.getByRole('button',{name:'Pause example'}).click()
  const stopped = await context.getAttribute('data-phase')
  await page.waitForTimeout(2300)
  await expect(context).toHaveAttribute('data-phase',stopped!)
  const target = page.locator('#product-target')
  await target.fill('My translation {player_name}')
  await page.emulateMedia({reducedMotion:'reduce'})
  await expect(target).toHaveValue('My translation {player_name}')
  const review = page.locator('.pd-review')
  await review.getByRole('button',{name:'Restore example',exact:true}).click()
  await expect(review.getByRole('button',{name:'Draft',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(review.locator('.pd-comment')).not.toBeVisible()
})

