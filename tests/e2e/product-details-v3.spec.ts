import {test, expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('Support links never overlap their explanation; scan rail stays clear of file text', async ({page}) => {
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/product')
  const copy = await page.locator('.sample-downloads > div:first-child > p').boundingBox()
  const link = await page.locator('.sample-inline-link').boundingBox()
  expect(link!.y).toBeGreaterThanOrEqual(copy!.y + copy!.height + 8)
  const beam = await page.locator('.pd-scan-beam').boundingBox()
  const text = await page.locator('.pd-scan-box code').nth(2).evaluate(el => {
    const range = document.createRange(); range.selectNodeContents(el)
    const box = range.getBoundingClientRect(); return {bottom:box.bottom}
  })
  expect(beam!.y).toBeGreaterThan(text.bottom + 4)
  const cta = await page.locator('.format-result > a').evaluate(el => getComputedStyle(el).backgroundColor)
  expect(cta).toBe('rgb(242, 245, 240)')
})

test('Product details keeps functional demos, stable layout and protected tokens', async ({page}) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.emulateMedia({reducedMotion: 'reduce'})
  await page.goto('/product')
  await expect(page.locator('h1')).toHaveText('Everything around the line.')
  const target = page.locator('#product-target')
  await target.fill('Translation without the required placeholder')
  await expect(page.locator('.pd-token')).toHaveAttribute('data-valid', 'false')
  await target.fill('Translation with {player_name}')
  await expect(page.locator('.pd-token')).toHaveAttribute('data-valid', 'true')
  const review = page.locator('.pd-review')
  await review.getByRole('button', {name:'Translated', exact:true}).click()
  await expect(review.getByRole('button', {name:'Translated', exact:true})).toHaveAttribute('aria-pressed','true')
  await review.getByRole('button', {name:'Comments', exact:true}).click()
  await expect(review.locator('.pd-comment')).not.toBeVisible()
  await page.locator('.pd-memory').getByRole('button', {name:'Use suggestion', exact:true}).click()
  await expect(page.locator('.pd-applied')).toBeVisible()
  await expect(page.locator('.friday-clock-secret-trigger')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('Product stories reserve space and replay clears manual state', async ({page}) => {
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.goto('/product')
  const review = page.locator('.pd-review')
  const before = await review.boundingBox()
  await review.getByRole('button',{name:'Comments',exact:true}).click()
  const after = await review.boundingBox()
  expect(after?.height).toBe(before?.height)
  await review.getByRole('button',{name:'Draft',exact:true}).click()
  await review.getByRole('button',{name:'Replay example',exact:true}).click()
  await expect(review.getByRole('button',{name:'Approved',exact:true})).toHaveAttribute('aria-pressed','true')
  const memory = page.locator('.pd-memory')
  const memoryBefore = await memory.boundingBox()
  await memory.getByRole('button',{name:'Use suggestion',exact:true}).click()
  expect((await memory.boundingBox())?.height).toBe(memoryBefore?.height)
  await memory.getByRole('button',{name:'Replay example',exact:true}).click()
  await expect(memory.getByRole('button',{name:'Use suggestion',exact:true})).toBeEnabled()
})

test('Product autoplay changes emphasis without moving adjacent sections', async ({page}, testInfo) => {
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto('/product')
  const context = page.locator('.pd-context')
  await context.scrollIntoViewIfNeeded()
  await expect(context).toHaveAttribute('data-visible','true')
  await expect(context).toHaveAttribute('data-phase','0')
  const initial = await context.boundingBox()
  await expect(context).toHaveAttribute('data-phase','1',{timeout:5000})
  expect(await context.boundingBox()).toEqual(initial)
  await context.getByRole('button',{name:'Pause example',exact:true}).click()
  await expect(context.getByRole('button',{name:'Replay example',exact:true})).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('product-context.png')})
  const review = page.locator('.pd-review')
  await review.scrollIntoViewIfNeeded()
  await expect(review).toHaveAttribute('data-visible','true')
  const reviewInitial = await review.boundingBox()
  await expect(review).toHaveAttribute('data-phase','1',{timeout:5000})
  expect(await review.boundingBox()).toEqual(reviewInitial)
  await expect(review.locator('.pd-comment')).toBeVisible()
})

test('Local workflow dots follow all four steps and animate only the current step', async ({page}) => {
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.goto('/product')
  const local = page.locator('.pd-local')
  await local.scrollIntoViewIfNeeded()
  await expect(local).toHaveAttribute('data-visible','true')
  await expect(local).toHaveAttribute('data-phase','2',{timeout:7000})
  await expect(local.locator('li').nth(2).locator('img')).toHaveAttribute('src',/flow-node0/)
  await expect(local.locator('li').nth(3).locator('img')).toHaveAttribute('src',/flow-node2/)
  expect(await local.locator('[data-active=true] img').evaluate(el => getComputedStyle(el).animationName)).toBe('pd-node-arrival')
  await expect(local).toHaveAttribute('data-phase','3',{timeout:4000})
  await expect(local.locator('li').nth(3).locator('img')).toHaveAttribute('src',/flow-node0/)
  await page.emulateMedia({reducedMotion:'reduce'})
  expect(await local.locator('[data-active=true] img').evaluate(el => getComputedStyle(el).animationName)).toBe('none')
})

